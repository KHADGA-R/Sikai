import '@angular/compiler';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const compile = path => ts.transpileModule(readFileSync(path, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, experimentalDecorators: true } }).outputText;
const url = js => 'data:text/javascript;base64,' + Buffer.from(js).toString('base64');
let stored = null;
let failWrite = false;
globalThis.localStorage = { getItem: () => stored, setItem: (_, value) => { if (failWrite) throw new Error('quota'); stored = value; } };
const taxonomyUrl = url(compile('src/app/core/categories.ts'));
const sampleUrl = url(compile('src/app/core/sample-data.ts'));
const js = compile('src/app/admin/admin-course.service.ts').replace("'@angular/core'", JSON.stringify(import.meta.resolve('@angular/core'))).replace("'../core/sample-data'", JSON.stringify(sampleUrl)).replace("'../core/categories'", JSON.stringify(taxonomyUrl));
const { AdminCourseService, validCourse } = await import(url(js));
const store = new AdminCourseService();
const initial = store.courses().length;
assert.ok(initial > 0);
const course = { ...store.courses()[0], id: 9999, title: 'Admin testing course' };
store.save(course, false);
assert.equal(store.courses().length, initial + 1);
assert.equal(new AdminCourseService().courses().find(c => c.id === 9999).title, course.title);
store.save({ ...course, title: 'Updated course', price: 0, isFree: true, published: false }, true);
assert.equal(store.courses().find(c => c.id === 9999).title, 'Updated course');
assert.throws(() => store.save({ ...course, price: -1 }, true));
assert.throws(() => store.save({ ...course, lessons: 1.5 }, true));
assert.throws(() => store.save({ ...course, title: '   ' }, true));
assert.throws(() => store.save(course, false));
assert.equal(validCourse({...course, category:'Music', subcategory:'Musical Instruments'}), true);
assert.equal(validCourse({...course, category:'Music', subcategory:'Nepali'}), false);
const before = JSON.stringify(store.courses());
failWrite = true;
assert.throws(() => store.delete(9999));
assert.equal(JSON.stringify(store.courses()), before);
failWrite = false;
store.delete(9999);
assert.ok(!new AdminCourseService().courses().some(c => c.id === 9999));
for (const c of [...store.courses()]) store.delete(c.id);
assert.equal(new AdminCourseService().courses().length, 0);
stored = JSON.stringify([{...course, category:'Development', subcategory:undefined}]);
const migrated = new AdminCourseService().courses()[0];
assert.equal(migrated.category, 'Skills & Training');
assert.equal(migrated.subcategory, 'IT & Technology');
stored = '{broken';
const broken = new AdminCourseService();
assert.ok(broken.error());
assert.throws(() => broken.save(course, false));
assert.equal(stored, '{broken');
console.log('Passed: seeding, create, update, persistence, numeric/title validation, duplicate IDs, failed-write consistency, delete, empty-library persistence, corrupt-storage protection.');
