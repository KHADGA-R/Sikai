@Injectable({ providedIn: 'root' })
export class LanguageService {
  private readonly selection = signal<'en' | 'ne'>('en');
  readonly current = this.selection.asReadonly();

  constructor() {
    try {
      if (localStorage.getItem('sikai.language') === 'ne') this.selection.set('ne');
    } catch { /* Storage is optional. */ }
  }

  set(language: 'en' | 'ne'): void {
    this.selection.set(language);
    try {
      localStorage.setItem('sikai.language', language);
    } catch { /* The current selection still applies. */ }
  }

  translate(text: string, values?: Record<string, string | number>): string {
    const label = this.current() === 'ne' && Object.hasOwn(pageLabels, text)
      ? pageLabels[text as keyof typeof pageLabels]
      : text;
    return values ? label.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token)) : label;
  }
}
